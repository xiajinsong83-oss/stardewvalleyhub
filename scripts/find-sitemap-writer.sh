#!/usr/bin/env bash
# find-sitemap-writer.sh — 定位“破坏源”脚本
# 背景: 顶层 sitemap.xml 被旧内容+AI注释污染，典型元凶是某个脚本用 r+b/追加模式
#       写入 sitemap.xml 且未 truncate。本脚本在项目里搜索可能写入 sitemap.xml 的工具。
# 用法: bash find-sitemap-writer.sh <你的Hugo项目根目录>
# 说明: 输出候选文件与命中行号；最终修复需你人工确认后修改对应脚本。

set -u

ROOT="${1:-.}"

if [ ! -d "$ROOT" ]; then
  echo "FAIL  目录不存在: $ROOT"
  echo "用法: bash find-sitemap-writer.sh /你的Hugo项目根目录"
  exit 1
fi

echo "===== 在 $ROOT 中排查写入 sitemap.xml 的脚本 ====="
echo ""

echo "--- [1/3] 直接引用 sitemap.xml 的脚本文件 ---"
grep -rln --include='*.py' --include='*.sh' --include='*.js' --include='*.ts' \
  -e 'sitemap\.xml' "$ROOT" 2>/dev/null | grep -v '/public/' | grep -v node_modules | grep -v '.git/' || echo "  (未找到)"

echo ""
echo "--- [2/3] 危险写入模式（r+b / 追加 / seek+write 且可能无 truncate）---"
grep -rn --include='*.py' --include='*.sh' --include='*.js' --include='*.ts' \
  -e "'r+b'" -e '"r+b"' \
  -e "open(.*['\"]a['\"]" \
  -e "\.seek(" \
  -e "truncate" \
  "$ROOT" 2>/dev/null | grep -v node_modules | grep -v '.git/' | grep -v '.venv/' || echo "  (未找到候选)"

echo ""
echo "--- [3/3] AI 生成痕迹（与损坏文件尾部注释同源的关键词）---"
grep -rn --include='*.py' --include='*.sh' --include='*.js' --include='*.ts' --include='*.md' \
  -e '内容由AI生成' -e '由AI生成' -e 'AI生成' -e 'generated by AI' -e 'ai_generated' \
  "$ROOT" 2>/dev/null | grep -v node_modules | grep -v '.git/' | head -30 || echo "  (未找到)"

echo ""
echo "===== 排查完成 ====="
echo "修复原则: 任何脚本都不得直接改写 public/ 下 Hugo 生成的 sitemap.xml；"
echo "         AI 生成的页面清单请输出到独立文件(如 ai-pages.xml)，或写入后强制 f.truncate()。"
